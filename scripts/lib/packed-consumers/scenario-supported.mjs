import assert from "node:assert/strict";
import { mkdirSync, readFileSync } from "node:fs";
import path from "node:path";
import {
  packedDependenciesFor,
  writeConsumerManifest,
  writeEffectConsumerSource,
  writeGeneratedCommandTsconfig,
  writeRuntimeConfig,
  writeStrictNpmrc,
} from "./fixtures.mjs";
import {
  assertGeneratorEffectPeerContract,
  assertPackedPackages,
  assertPlatformNodeSharedIdentity,
  assertSingleEffectIdentity,
} from "./graph.mjs";
import {
  contract,
  installFixture,
  readJson,
  rootPackage,
  run,
  runNode,
  writeJson,
} from "./runtime.mjs";

/** @param {string} fixtureRoot @returns {string} */
const addPluginScaffold = fixtureRoot => {
  const scaffoldRoot = path.join(fixtureRoot, "scaffolded-plugin");
  run({
    args: [
      "exec",
      "typeweaver",
      "add",
      "plugin",
      "--name",
      "packed-starter",
      "--target",
      scaffoldRoot,
    ],
    cwd: fixtureRoot,
  });
  return scaffoldRoot;
};

/** @param {{ archives: ReadonlyMap<string, string>, packages: readonly import("../tooling-types.mjs").PublicPackage[], scaffoldRoot: string }} options @returns {void} */
const configureScaffoldedPlugin = ({ archives, packages, scaffoldRoot }) => {
  const scaffoldManifestPath = path.join(scaffoldRoot, "package.json");
  const scaffoldManifest = readJson(scaffoldManifestPath);
  const packedDependencies = packedDependenciesFor({ archives, packages });
  assert.equal(
    scaffoldManifest.peerDependencies?.["effect"],
    contract.peerRange
  );
  assert(
    !/workspace:|catalog:/.test(JSON.stringify(scaffoldManifest)),
    "plugin scaffold retained a workspace-only dependency specifier"
  );
  writeJson(scaffoldManifestPath, {
    ...scaffoldManifest,
    packageManager: rootPackage.packageManager,
    pnpm: { overrides: packedDependencies },
  });
  writeStrictNpmrc(scaffoldRoot);
};

/** @param {string} scaffoldRoot @returns {void} */
const assertScaffoldGeneratedOutput = scaffoldRoot =>
  assert.equal(
    readFileSync(
      path.join(
        scaffoldRoot,
        "test",
        "fixture",
        "generated",
        "packed-starter",
        "generated.txt"
      ),
      "utf8"
    ),
    "generated by packed-starter\n"
  );

/** @param {{ archives: ReadonlyMap<string, string>, effectVersion: string, fixtureRoot: string, packages: readonly import("../tooling-types.mjs").PublicPackage[] }} options @returns {void} */
export const verifyScaffoldedPlugin = ({
  archives,
  effectVersion,
  fixtureRoot,
  packages,
}) => {
  const scaffoldRoot = addPluginScaffold(fixtureRoot);
  configureScaffoldedPlugin({ archives, packages, scaffoldRoot });
  installFixture(scaffoldRoot);
  assertPackedPackages({ fixtureRoot: scaffoldRoot, packages });
  assertGeneratorEffectPeerContract(scaffoldRoot);
  assertSingleEffectIdentity({
    effectVersion,
    fixtureRoot: scaffoldRoot,
    includeCompatPlugin: false,
    packages,
  });
  run({ args: ["run", "check"], cwd: scaffoldRoot });
  assertScaffoldGeneratedOutput(scaffoldRoot);
};

/** @param {{ fixtureRoot: string, outputRoot: string }} options @returns {void} */
export const verifyGeneratedCommandConsumer = ({ fixtureRoot, outputRoot }) => {
  writeEffectConsumerSource(outputRoot);
  const { generatedTsconfig, generatedDist } = writeGeneratedCommandTsconfig({
    fixtureRoot,
    outputRoot,
  });
  run({
    args: ["exec", "tsc", "--project", generatedTsconfig],
    cwd: fixtureRoot,
  });
  assert.equal(
    runNode({
      args: [
        "--input-type=module",
        "--eval",
        `await import(${JSON.stringify(path.join(generatedDist, "index.js"))}); if (process.exitCode !== undefined) throw new Error("generated barrel executed the command CLI"); process.stdout.write("generated-import-ok\\n");`,
      ],
      cwd: fixtureRoot,
    }),
    "generated-import-ok\n"
  );
  assert.match(
    runNode({
      args: [path.join(generatedDist, "command", "cli.mjs"), "--help"],
      cwd: fixtureRoot,
    }),
    /ping\s+Ping/
  );
  assert.equal(
    runNode({
      args: [path.join(generatedDist, "effect-consumer.js")],
      cwd: fixtureRoot,
    }),
    "effect-adapter-ok\n"
  );
};

/** @param {string} fixtureRoot @returns {void} */
const assertProgrammaticImports = fixtureRoot => {
  const importCheck =
    'const api = await import("@rexeus/typeweaver"); if (typeof api.Generator?.generate !== "function" || typeof api.effectRuntime?.runPromise !== "function") throw new Error("missing programmatic API"); if (process.exitCode !== undefined) throw new Error("package import changed process.exitCode"); process.stdout.write("import-ok\\n");';
  const requireCheck =
    'const api = require("@rexeus/typeweaver"); if (typeof api.Generator?.generate !== "function" || typeof api.effectRuntime?.runPromise !== "function") throw new Error("missing programmatic API"); if (process.exitCode !== undefined) throw new Error("package require changed process.exitCode"); process.stdout.write("require-ok\\n");';
  assert.equal(
    runNode({
      args: ["--input-type=module", "--eval", importCheck],
      cwd: fixtureRoot,
    }),
    "import-ok\n"
  );
  assert.equal(
    runNode({ args: ["--eval", requireCheck], cwd: fixtureRoot }),
    "require-ok\n"
  );
};

/** @param {{ archives: ReadonlyMap<string, string>, effectVersion: string, matrixRoot: string, packages: readonly import("../tooling-types.mjs").PublicPackage[] }} options @returns {void} */
export const verifySupportedConsumer = ({
  archives,
  effectVersion,
  matrixRoot,
  packages,
}) => {
  const fixtureRoot = path.join(matrixRoot, `effect-${effectVersion}`);
  mkdirSync(fixtureRoot, { recursive: true });
  writeConsumerManifest({ archives, effectVersion, fixtureRoot, packages });
  installFixture(fixtureRoot);
  assertPackedPackages({ fixtureRoot, packages });
  assertGeneratorEffectPeerContract(fixtureRoot);
  assertPlatformNodeSharedIdentity({ fixtureRoot });
  assertSingleEffectIdentity({ effectVersion, fixtureRoot, packages });
  run({
    args: ["exec", "tsc", "--project", "tsconfig.json"],
    cwd: fixtureRoot,
  });
  assertProgrammaticImports(fixtureRoot);
  const { configPath, outputRoot } = writeRuntimeConfig(fixtureRoot);
  const output = run({
    args: [
      "exec",
      "typeweaver",
      "generate",
      "--config",
      configPath,
      "--no-format",
    ],
    cwd: fixtureRoot,
  });
  assert.match(output, /Successfully loaded 5 plugin/);
  assert.equal(
    readFileSync(path.join(outputRoot, "packed-compat", "result.txt"), "utf8"),
    "packed-consumer-ok\n"
  );
  verifyGeneratedCommandConsumer({ fixtureRoot, outputRoot });
  verifyScaffoldedPlugin({ archives, effectVersion, fixtureRoot, packages });
};
